// S205 embedded UI shader set.
// Compiled from the canonical GLSL in build/s205_shaders/*.{vert,frag} with
// glslangValidator 16.x on the Ubuntu VM (the repo's declared shader-authoring
// toolchain), validated with spirv-val, then debug-stripped with spirv-opt
// --strip-debug. The raw word arrays are generated from the validated binaries
// (build/s205_shaders/emit.py + gen.sh) so they are EXACTLY the device-shader
