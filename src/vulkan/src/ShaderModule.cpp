// auditable source of truth in build/s205_shaders/ + the header comments.
//
// === UI VERTEX (ui_vertex_spirv) ===
//   #version 450
//   layout(push_constant) uniform PushConstants { mat4 mvp; vec4 uiAndPad;
//       vec4 color; vec4 params; vec4 size; } pc;
//   layout(location = 0) in vec2 position;
//   layout(location = 1) in vec2 uv;
//   layout(location = 2) in vec4 vcolor;
//   layout(location = 0) out vec2 vUv;
//   layout(location = 1) out vec4 vColor;
//   void main() {
//       gl_Position = pc.mvp * vec4(position, 0.0, 1.0);
//       vUv = uv; vColor = vcolor;
//   }
//
// === SDF TEXT FRAGMENT (sdf_text_fragment_spirv) ===
//   #version 450
//   layout(set = 0, binding = 0) uniform sampler2D tex;
//   // pc: mvp / uiAndPad / color / params (params.x = aa) / size
//   void main() {
//       float dlin = texture(tex, vUv).r;
//       float dist01 = pow(dlin, 1.0 / 2.2);   // undo the atlas sRGB decode
//       float aa = max(pc.params.x, 0.0001);
//       float alpha = clamp((dist01 - (0.5 - aa)) / (2.0 * aa), 0.0, 1.0);
//       outColor = vec4(pc.color.rgb, pc.color.a * alpha) * vColor;
//   }
//
// === SOLID COLOR FRAGMENT (solid_color_fragment_spirv) ===
//   void main() { outColor = pc.color * vColor; }
//
// === BORDER FRAGMENT (border_fragment_spirv) ===
//   float sdRoundBox(vec2 p, vec2 b, float r) {
//       vec2 q = abs(p) - b + vec2(r);
//       return length(max(q, 0.0)) + min(max(q.x, q.y), 0.0) - r;
//   }
//   void main() {
//       float t = clamp(pc.params.x, 0.0, 0.5);  // thickness01
//       float r = clamp(pc.params.y, 0.0, 0.5);  // radius01
//       float feather = pc.params.z; float aa = pc.params.w;
//       vec2 p = vUv - vec2(0.5);
//       float so = sdRoundBox(p, vec2(0.5), r);
//       float si = sdRoundBox(p, vec2(0.5 - t), max(r - t, 0.0));
//       float dist = min(-so, si);
