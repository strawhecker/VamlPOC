#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
parity_sync_check.py — S642 GENERIC CAPABILITY PARITY: the SYNC-TOKEN enforcer.

The "keep both in sync" mechanism: for EVERY capability in the single-source catalogue
(tools/capability_catalogue.json), assert that:
  1. OUR side has emitted it (our-status present + parity=yes or a named gap), and
  2. the WPF-emitter side has declared it (wpf-status present + parity=yes or a named gap),
  3. the matrix (docs/PARITY_MATRIX.md — regenerated by parity_matrix_gen.py) agrees.

EVERY capability carries a SYNC TOKEN: a capability may only be introduced by updating
OUR side AND the WPF-emitter side AND the matrix IN THE SAME STEP (the S642 contract).
This script fails LOUDLY on any drift — never silent.

This is tooling-only (a repo-resident script, like parity_matrix_gen.py). The C++ half of
the sync token (the headless catalogue test) lives in vaml-presentation-tests.

Usage:  python parity_sync_check.py [--catalogue tools/capability_catalogue.json]
                                    [--matrix docs/PARITY_MATRIX.md]
"""

import argparse
import json
import re
import sys

LEGAL_STATES = {"introduced", "done", "planned", "out-of-scope"}


def _fail(msg):
    print("PARITY SYNC CHECK: FAIL — " + msg)
    return False


def check(catalogue_path, matrix_path):
    with open(catalogue_path, "r", encoding="utf-8") as fh:
        cat = json.load(fh)

    cap = cat.get("capabilities", [])
    if not isinstance(cap, list) or not cap:
        return _fail("catalogue has no 'capabilities' list")

    with open(matrix_path, "r", encoding="utf-8", errors="replace") as fh:
        matrix_text = fh.read()

    ok = True
    for c in cap:
        cid = c.get("id", "")
        our = c.get("our", "")
        wpf = c.get("wpf", "")
        parity = c.get("parity", "")
        gap = c.get("gap", "")

        if not cid:
            ok = _fail("a capability row is missing its 'id'") and ok
            continue
        if our not in LEGAL_STATES:
            ok = _fail("capability %s: our-side status '%s' blank/unknown" % (cid, our)) and ok
        if wpf not in LEGAL_STATES:
            ok = _fail("capability %s: WPF-side status '%s' blank/unknown" % (cid, wpf)) and ok
        if parity not in ("yes", "no"):
            ok = _fail("capability %s: parity '%s' must be yes|no" % (cid, parity)) and ok
        if parity == "no" and not gap:
            ok = _fail("capability %s: parity=no but no named gap (never silent)" % cid) and ok

        # The matrix must contain a row for this capability (the derived agreement).
        row_re = re.compile(r"^\|\s*`" + re.escape(cid) + r"`\s*\|", re.M)
        if not row_re.search(matrix_text):
            ok = _fail("capability %s: no row in " % cid + matrix_path +
                       " (regenerate via parity_matrix_gen.py)") and ok

    n = len(cap)
    if ok:
        print(f"PARITY SYNC CHECK: OK — {n} capabilities in sync (our + WPF + matrix agree)")
    return ok


def main():
    ap = argparse.ArgumentParser(description="PARITY SYNC TOKEN enforcer (never silent)")
    ap.add_argument("--catalogue", default="tools/capability_catalogue.json")
    ap.add_argument("--matrix", default="docs/PARITY_MATRIX.md")
    args = ap.parse_args()
    if not check(args.catalogue, args.matrix):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
